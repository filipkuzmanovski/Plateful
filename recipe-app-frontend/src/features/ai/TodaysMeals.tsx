import { useEffect, useMemo, useState } from 'react';
import { Link } from 'react-router';
import { useQuery } from '@tanstack/react-query';
import { Clock, Sparkles } from 'lucide-react';
import { dailyMealsQueryKey, getDailyMeals } from '@/api/ai';
import { useAuth } from '@/auth/AuthProvider';
import { formatMealDate, localIsoDate } from '@/lib/localDate';
import type { GeneratedRecipeSummary, MealType } from '@/lib/types';

const POLL_MS = 3_000;
const GIVE_UP_MS = 2 * 60_000;
const MEALS: { key: MealType; label: string }[] = [
  { key: 'breakfast', label: 'Breakfast' },
  { key: 'lunch', label: 'Lunch' },
  { key: 'dinner', label: 'Dinner' },
];

const UNAVAILABLE = "Today's meals aren't available yet. Try again later.";

/** The "Today's meals" strip on the home page. Renders for fully set-up users only. */
export function TodaysMeals() {
  const { status } = useAuth();
  if (status !== 'ready') return null;
  return <Strip />;
}

function Strip() {
  const { profile } = useAuth();
  const date = useMemo(() => localIsoDate(), []);
  const [gaveUp, setGaveUp] = useState(false);

  const query = useQuery({
    queryKey: dailyMealsQueryKey(profile?.id, date),
    queryFn: () => getDailyMeals(date),
    retry: false,
    refetchOnWindowFocus: false,
    refetchInterval: (q) => (q.state.data?.status === 'generating' && !gaveUp ? POLL_MS : false),
  });

  // Stop waiting 2 minutes after the first "generating" answer.
  const generating = query.data?.status === 'generating';
  useEffect(() => {
    if (!generating) return;
    const timer = setTimeout(() => setGaveUp(true), GIVE_UP_MS);
    return () => clearTimeout(timer);
  }, [generating]);

  const meals = query.data?.status === 'ready' ? query.data.meals : undefined;
  const shown = MEALS.filter((m) => meals?.[m.key]);

  let body;
  if (query.isError || (generating && gaveUp) || query.data?.status === 'unavailable' || (query.data?.status === 'ready' && shown.length === 0)) {
    body = <p className="text-[15px] text-ink-soft">{UNAVAILABLE}</p>;
  } else if (query.isPending || generating) {
    body = (
      <>
        <p role="status" className="mb-2 text-[15px] text-ink-soft">Making today's meals...</p>
        <div aria-hidden="true">
          {MEALS.map((m) => (
            <div key={m.key} className="flex items-center gap-4 border-b border-dotted border-rule py-4 last:border-b-0">
              <div className="h-4 w-16 animate-pulse rounded-sm bg-tint sm:w-24" />
              <div className="h-5 flex-1 animate-pulse rounded-sm bg-tint" />
              <div className="h-4 w-12 animate-pulse rounded-sm bg-tint" />
            </div>
          ))}
        </div>
      </>
    );
  } else {
    const fallbackDate = query.data?.fresh === false && query.data.date ? query.data.date : null;
    body = (
      <>
        {fallbackDate && (
          <p className="mb-2 text-[15px] text-ink-soft">From {formatMealDate(fallbackDate)}. Today's meals couldn't be made fresh.</p>
        )}
        <ol>
          {shown.map((m) => (
            <li key={m.key} className="border-b border-dotted border-rule last:border-b-0">
              <MealRow label={m.label} meal={meals![m.key]!} />
            </li>
          ))}
        </ol>
      </>
    );
  }

  return (
    <section aria-labelledby="todays-meals-heading" className="mb-8 sm:mb-10">
      {/* SectionHeading's look, with room for the label on the right. */}
      <div className="mb-2 flex flex-wrap items-baseline justify-between gap-x-4 gap-y-1 border-b border-ink pb-1.5">
        <h2 id="todays-meals-heading" className="font-serif text-[28px] font-medium tracking-[-0.015em] text-ink">
          Today's meals
        </h2>
        <span className="inline-flex items-center gap-1.5 text-[13px] text-ink-soft">
          <Sparkles aria-hidden="true" className="size-3.5" strokeWidth={2} />
          Generated by AI
        </span>
      </div>
      {body}
    </section>
  );
}

/** One menu line: label, title (with the description under it from `sm`), and the time on the right. */
function MealRow({ label, meal }: { label: string; meal: GeneratedRecipeSummary }) {
  return (
    <Link
      to={`/ai-recipes/${meal.id}`}
      className="group grid grid-cols-[minmax(0,1fr)_auto] gap-x-4 gap-y-0.5 py-4 sm:grid-cols-[6rem_minmax(0,1fr)_auto] sm:items-baseline"
    >
      <span className="col-start-1 row-start-1 text-[13px] font-semibold text-ink-soft">{label}</span>
      <span className="col-start-1 row-start-2 font-serif text-[18px] leading-snug font-medium text-ink group-hover:underline sm:col-start-2 sm:row-start-1">
        {meal.title}
      </span>
      <span className="line-clamp-1 text-[15px] text-ink-soft max-sm:hidden sm:col-start-2 sm:row-start-2">
        {meal.description}
      </span>
      <span className="col-start-2 row-span-2 row-start-1 inline-flex items-center gap-1 self-center text-[15px] text-ink-soft tabular-nums sm:col-start-3 sm:row-span-1 sm:self-baseline">
        <Clock aria-hidden="true" className="size-3.5" strokeWidth={1.75} />
        {meal.totalMinutes} min
      </span>
    </Link>
  );
}
