import { useEffect, useMemo, useState } from 'react';
import { Link } from 'react-router';
import { useQuery } from '@tanstack/react-query';
import { Clock, Sparkles } from 'lucide-react';
import { dailyMealsQueryKey, getDailyMeals } from '@/api/ai';
import { useAuth } from '@/auth/AuthProvider';
import { formatMealDate, localIsoDate } from '@/lib/localDate';
import type { GeneratedRecipeSummary, MealType } from '@/lib/types';

const POLL_MS = 3_000;
const GIVE_UP_MS = 2 * 60_000;
const MEALS: { key: MealType; label: string }[] = [
  { key: 'breakfast', label: 'Breakfast' },
  { key: 'lunch', label: 'Lunch' },
  { key: 'dinner', label: 'Dinner' },
];

const UNAVAILABLE = "Today's meals aren't available yet. Try again later.";

/** The "Today's meals" strip on the home page. Renders for fully set-up users only. */
export function TodaysMeals() {
  const { status } = useAuth();
  if (status !== 'ready') return null;
  return <Strip />;
}

function Strip() {
  const { profile } = useAuth();
  const date = useMemo(() => localIsoDate(), []);
  const [gaveUp, setGaveUp] = useState(false);

  const query = useQuery({
    queryKey: dailyMealsQueryKey(profile?.id, date),
    queryFn: () => getDailyMeals(date),
    retry: false,
    refetchOnWindowFocus: false,
    refetchInterval: (q) => (q.state.data?.status === 'generating' && !gaveUp ? POLL_MS : false),
  });

  // Stop waiting 2 minutes after the first "generating" answer.
  const generating = query.data?.status === 'generating';
  useEffect(() => {
    if (!generating) return;
    const timer = setTimeout(() => setGaveUp(true), GIVE_UP_MS);
    return () => clearTimeout(timer);
  }, [generating]);

  const meals = query.data?.status === 'ready' ? query.data.meals : undefined;
  const shown = MEALS.filter((m) => meals?.[m.key]);

  let body;
  if (query.isError || (generating && gaveUp) || query.data?.status === 'unavailable' || (query.data?.status === 'ready' && shown.length === 0)) {
    body = <p className="text-sm text-olive/70">{UNAVAILABLE}</p>;
  } else if (query.isPending || generating) {
    body = (
      <>
        <p role="status" className="mb-4 text-sm text-olive/70">Making today's meals...</p>
        <div aria-hidden="true" className="grid grid-cols-1 gap-4 sm:grid-cols-3">
          {MEALS.map((m) => (
            <div key={m.key} className="h-32 animate-pulse rounded-card bg-paper shadow-card ring-1 ring-sand/70" />
          ))}
        </div>
      </>
    );
  } else {
    const fallbackDate = query.data?.fresh === false && query.data.date ? query.data.date : null;
    body = (
      <>
        {fallbackDate && (
          <p className="mb-4 text-sm text-olive/70">From {formatMealDate(fallbackDate)}. Today's meals couldn't be made fresh.</p>
        )}
        <ul className="grid grid-cols-1 gap-4 sm:grid-cols-3">
          {shown.map((m) => (
            <li key={m.key} className="flex">
              <MealCard label={m.label} meal={meals![m.key]!} />
            </li>
          ))}
        </ul>
      </>
    );
  }

  return (
    <section aria-labelledby="todays-meals-heading" className="mb-8 sm:mb-10">
      <div className="mb-4 flex flex-wrap items-baseline justify-between gap-x-4 gap-y-1">
        <h2 id="todays-meals-heading" className="font-serif text-2xl font-semibold tracking-tight text-olive">
          Today's meals
        </h2>
        <span className="inline-flex items-center gap-1.5 text-xs font-semibold text-olive/60">
          <Sparkles aria-hidden="true" className="size-3.5" strokeWidth={2} />
          Generated by AI
        </span>
      </div>
      {body}
    </section>
  );
}

function MealCard({ label, meal }: { label: string; meal: GeneratedRecipeSummary }) {
  return (
    <Link
      to={`/ai-recipes/${meal.id}`}
      className="group flex flex-1 flex-col gap-2 rounded-card bg-paper p-4 shadow-card ring-1 ring-sand/70 transition duration-300 ease-out hover:-translate-y-1 hover:shadow-lift hover:ring-sand"
    >
      <span className="text-xs font-bold tracking-wider text-terracotta uppercase">{label}</span>
      <span className="line-clamp-2 font-serif text-lg leading-snug font-semibold text-olive transition-colors group-hover:text-terracotta">
        {meal.title}
      </span>
      <span className="line-clamp-2 text-sm text-olive/70">{meal.description}</span>
      <span className="mt-auto inline-flex items-center gap-1 pt-1 text-sm text-olive/70 tabular-nums">
        <Clock aria-hidden="true" className="size-3.5" strokeWidth={1.75} />
        {meal.totalMinutes} min
      </span>
    </Link>
  );
}
