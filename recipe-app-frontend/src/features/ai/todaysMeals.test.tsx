import { http, HttpResponse } from 'msw';
import { act, cleanup, screen } from '@testing-library/react';
import { server } from '@/test/server';
import { renderApp } from '@/test/utils';
import { pageOf, profileFixture } from '@/test/fixtures';
import { expectNoEmoji } from '@/test/noEmoji';
import { localIsoDate } from '@/lib/localDate';
import type { DailyMeals, GeneratedRecipeSummary, MealType } from '@/lib/types';

const BASE = 'http://localhost:8080';
const DAILY = `${BASE}/api/users/me/daily-meals`;
const UNAVAILABLE = "Today's meals aren't available yet. Try again later.";
const WAITING = "Making today's meals...";

const mocks = vi.hoisted(() => ({ session: null as unknown }));

vi.mock('@/auth/supabaseClient', () => ({
  supabase: {
    auth: {
      getSession: async () => ({ data: { session: mocks.session } }),
      onAuthStateChange: () => ({ data: { subscription: { unsubscribe() {} } } }),
      signOut: async () => {},
    },
  },
}));

function summary(mealType: MealType, title: string, totalMinutes = 25): GeneratedRecipeSummary {
  return { id: `id-${mealType}`, kind: 'daily', mealType, title, description: `About ${title}.`, totalMinutes, savedAt: null };
}

const READY: DailyMeals = {
  status: 'ready', date: localIsoDate(), fresh: true,
  meals: {
    breakfast: summary('breakfast', 'Oat Porridge', 15),
    lunch: summary('lunch', 'Lentil Soup'),
    dinner: summary('dinner', 'Baked Cod', 40),
  },
};

function signIn(profile = profileFixture) {
  mocks.session = { access_token: 't', user: { id: 'u-1', email: 'jane@example.com' } };
  server.use(
    http.get(`${BASE}/api/users/me`, () => HttpResponse.json(profile)),
    http.get(`${BASE}/api/recipes`, () => HttpResponse.json(pageOf([]))),
  );
}

/** Answers each request with the next body (the last one repeats) and records the `date` asked for. */
function serve(...bodies: DailyMeals[]) {
  let i = 0;
  const dates: (string | null)[] = [];
  server.use(http.get(DAILY, ({ request }) => {
    dates.push(new URL(request.url).searchParams.get('date'));
    return HttpResponse.json(bodies[Math.min(i++, bodies.length - 1)]);
  }));
  return dates;
}

beforeEach(() => { mocks.session = null; });

describe("Today's meals strip", () => {
  it('shows Breakfast, Lunch and Dinner cards linking to the AI recipes', async () => {
    signIn();
    serve(READY);
    renderApp('/');

    expect(await screen.findByRole('heading', { level: 2, name: "Today's meals" })).toBeInTheDocument();
    const links = await screen.findAllByRole('link', { name: /Oat Porridge|Lentil Soup|Baked Cod/ });
    expect(links.map((l) => l.getAttribute('href'))).toEqual(['/ai-recipes/id-breakfast', '/ai-recipes/id-lunch', '/ai-recipes/id-dinner']);
    expect(links[0]).toHaveTextContent('Breakfast');
    expect(links[0]).toHaveTextContent('About Oat Porridge.');
    expect(links[0]).toHaveTextContent('15 min');
    expect(links[1]).toHaveTextContent('Lunch');
    expect(links[2]).toHaveTextContent('Dinner');
    expect(links[2]).toHaveTextContent('40 min');
    expect(screen.getByText('Generated by AI')).toBeInTheDocument();
    expect(screen.queryByText(/couldn't be made fresh/)).not.toBeInTheDocument();
    expectNoEmoji();
  });

  it('asks for the local date', async () => {
    signIn();
    const dates = serve(READY);
    renderApp('/');
    await screen.findByText('Oat Porridge');
    expect(dates).toEqual([localIsoDate()]);
  });

  it('shows the fallback date when the meals are not fresh', async () => {
    signIn();
    serve({ ...READY, date: '2026-10-28', fresh: false });
    renderApp('/');
    expect(await screen.findByText("From 28 October. Today's meals couldn't be made fresh.")).toBeInTheDocument();
    expect(screen.getByText('Oat Porridge')).toBeInTheDocument();
    expectNoEmoji();
  });

  it('shows the unavailable text when there is nothing to show', async () => {
    signIn();
    serve({ status: 'unavailable' });
    renderApp('/');
    expect(await screen.findByText(UNAVAILABLE)).toBeInTheDocument();
    expectNoEmoji();
  });

  it.each([503, 409])('shows the unavailable text on a %i', async (status) => {
    signIn();
    server.use(http.get(DAILY, () => HttpResponse.json({ code: 'x', detail: 'nope' }, { status })));
    renderApp('/');
    expect(await screen.findByText(UNAVAILABLE)).toBeInTheDocument();
    expect(screen.queryByRole('alert')).not.toBeInTheDocument();
  });

  it('is not rendered, and asks for nothing, for anonymous users', async () => {
    const dates = serve(READY);
    renderApp('/');
    await screen.findByText(/cook something/i);
    expect(screen.queryByRole('heading', { name: "Today's meals" })).not.toBeInTheDocument();
    expect(dates).toEqual([]);
  });

  it('is not rendered, and asks for nothing, before preferences are set', async () => {
    signIn({ ...profileFixture, hasPreferences: false });
    const dates = serve(READY);
    renderApp('/');
    await screen.findByRole('heading', { name: 'Your food preferences' });
    expect(screen.queryByRole('heading', { name: "Today's meals" })).not.toBeInTheDocument();
    expect(dates).toEqual([]);
  });
});

describe("Today's meals while generating", () => {
  // Testing Library only drains its own timers under fake timers when it sees a `jest` global.
  beforeAll(() => { (globalThis as { jest?: unknown }).jest = { advanceTimersByTime: vi.advanceTimersByTime }; });
  afterAll(() => { delete (globalThis as { jest?: unknown }).jest; });
  beforeEach(() => { vi.useFakeTimers({ shouldAdvanceTime: false, toFake: ['setTimeout', 'clearTimeout', 'setInterval', 'clearInterval', 'Date'] }); });
  afterEach(() => { cleanup(); vi.useRealTimers(); });

  const advance = (ms: number) => act(async () => { await vi.advanceTimersByTimeAsync(ms); });

  it('shows the waiting text, then the meals after the next poll', async () => {
    signIn();
    const dates = serve({ status: 'generating' }, READY);
    renderApp('/');
    await advance(100);

    expect(screen.getByText(WAITING)).toBeInTheDocument();
    expect(screen.queryByText('Oat Porridge')).not.toBeInTheDocument();
    expect(dates).toHaveLength(1);
    expectNoEmoji();

    await advance(3_000);
    expect(dates).toHaveLength(2);
    expect(screen.getByText('Oat Porridge')).toBeInTheDocument();
    expect(screen.queryByText(WAITING)).not.toBeInTheDocument();

    await advance(10_000); // ready: no more polling
    expect(dates).toHaveLength(2);
  });

  it('stops polling after 2 minutes and shows the unavailable text', async () => {
    signIn();
    const dates = serve({ status: 'generating' });
    renderApp('/');
    await advance(100);
    expect(screen.getByText(WAITING)).toBeInTheDocument();

    await advance(60_000);
    expect(screen.getByText(WAITING)).toBeInTheDocument();
    expect(dates.length).toBeGreaterThan(10);

    await advance(60_000);
    expect(screen.getByText(UNAVAILABLE)).toBeInTheDocument();
    expect(screen.queryByText(WAITING)).not.toBeInTheDocument();
    const polls = dates.length;
    await advance(30_000);
    expect(dates).toHaveLength(polls);
  });
});
