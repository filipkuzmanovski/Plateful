describe('aiErrorMessage', () => {
  const err = (status: number, detail: string, code?: string) => new ApiError(status, detail, undefined, code);

  it('maps each code to its message', () => {
    expect(aiErrorMessage(err(409, 'x', 'no_preferences'))).toBe('Set your food preferences first.');
    expect(aiErrorMessage(err(429, 'x', 'daily_limit'))).toBe("You've used today's 10 AI recipes. More tomorrow.");
    expect(aiErrorMessage(err(503, 'x', 'ai_quota'))).toBe('The free AI limit is reached for now. Try again later.');
    expect(aiErrorMessage(err(503, 'x', 'ai_unavailable'))).toBe("The AI service isn't responding. Try again in a minute.");
    expect(aiErrorMessage(err(503, 'x', 'ai_not_configured'))).toBe("AI features aren't set up on this server.");
    expect(aiErrorMessage(err(422, 'x', 'generation_failed')))
      .toBe("Couldn't make a safe new recipe from these. Try changing the ingredients.");
  });

  it('uses the detail for invalid_request and unknown codes, and a generic text otherwise', () => {
    expect(aiErrorMessage(err(400, 'Give 2 to 15 ingredients.', 'invalid_request'))).toBe('Give 2 to 15 ingredients.');
    expect(aiErrorMessage(err(500, 'Boom', 'other'))).toBe('Boom');
    expect(aiErrorMessage(new Error('network'))).toBe('Something went wrong. Please try again.');
  });
});

describe('ApiError conflicts', () => {
  it('keeps the conflicts list from a problem body', async () => {
    signedIn();
    const { generateRecipe } = await import('@/api/ai');
    server.use(
      http.post(`${BASE}/api/users/me/ai-recipes/generate`, () =>
        HttpResponse.json(
          { detail: 'Some ingredients clash.', code: 'invalid_request', conflicts: [{ ingredient: 'milk', reason: 'allergy: Milk' }] },
          { status: 400 },
        )),
    );
    const e = await generateRecipe({ ingredients: ['milk', 'rice'], mealType: null, onlyWhatIHave: false }).catch((x) => x);
    expect(e).toBeInstanceOf(ApiError);
    expect((e as ApiError).conflicts).toEqual([{ ingredient: 'milk', reason: 'allergy: Milk' }]);
  });
});
