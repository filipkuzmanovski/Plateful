import { http, HttpResponse } from 'msw';
import { screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { server } from '@/test/server';
import { renderApp } from '@/test/utils';
import { profileFixture } from '@/test/fixtures';
import { expectNoEmoji } from '@/test/noEmoji';
import { ApiError } from '@/api/client';
import type { GeneratedRecipe } from '@/lib/types';
import { aiErrorMessage } from './aiMessages';

const BASE = 'http://localhost:8080';

const mocks = vi.hoisted(() => ({ session: null as unknown }));

vi.mock('@/auth/supabaseClient', () => ({
  supabase: {
    auth: {
      getSession: async () => ({ data: { session: mocks.session } }),
      onAuthStateChange: () => ({ data: { subscription: { unsubscribe() {} } } }),
      signOut: async () => {},
    },
  },
}));

function recipeFor(overrides: Partial<GeneratedRecipe> = {}): GeneratedRecipe {
  return {
    id: 'a-1', kind: 'cook', mealType: 'dinner', title: 'Tomato Egg Skillet',
    description: 'Eggs baked in a spiced tomato sauce.', servings: 2, prepMinutes: 10, cookMinutes: 20,
    cuisine: 'greek',
    ingredients: [
      { name: 'eggs', amount: '4', extra: false },
      { name: 'tomatoes', amount: '3 large', extra: false },
      { name: 'paprika', amount: '1 tsp', extra: true },
    ],
    steps: ['Simmer the tomatoes.', 'Crack in the eggs and cover.'],
    diets: { vegetarian: true, vegan: false, glutenFree: true, dairyFree: false },
    allergens: [{ key: 'milk', label: 'Milk' }, { key: 'eggs', label: 'Eggs' }],
    saved: false, createdAt: '2026-10-31T10:00:00Z', provider: 'groq',
    origin: null, swaps: [],
    ...overrides,
  };
}

function signedIn() {
  mocks.session = { access_token: 't', user: { id: 'u-1', email: 'jane@example.com' } };
  server.use(
    http.get(`${BASE}/api/users/me`, () => HttpResponse.json(profileFixture)),
    http.get(`${BASE}/api/recipes/cuisines`, () =>
      HttpResponse.json([{ key: 'greek', label: 'Greek Isles', region: 'europe', seas: [], count: 3 }])),
  );
}

const AI_NOTE = 'Generated by AI. Not checked by a person. Use your judgement, especially with meat, eggs and allergens.';

describe('AI recipe page', () => {
  it('shows the note, header facts, allergens, diets, extras, numbered steps and provider', async () => {
    signedIn();
    server.use(http.get(`${BASE}/api/users/me/ai-recipes/a-1`, () => HttpResponse.json(recipeFor())));
    renderApp('/ai-recipes/a-1');

    expect(await screen.findByRole('heading', { name: 'Tomato Egg Skillet' })).toBeInTheDocument();
    expect(screen.getByText(AI_NOTE)).toBeInTheDocument();
    expect(await screen.findByText('Greek Isles')).toBeInTheDocument();
    expect(screen.queryByText('greek')).not.toBeInTheDocument();
    expect(screen.getByText('Contains: Milk, Eggs')).toBeInTheDocument();
    expect(screen.getByText('Vegetarian')).toBeInTheDocument();
    expect(screen.getByText('Gluten-free')).toBeInTheDocument();
    expect(screen.queryByText('Vegan')).not.toBeInTheDocument();
    expect(screen.queryByText('Dairy-free')).not.toBeInTheDocument();

    expect(screen.getByRole('heading', { name: "You'll also need" })).toBeInTheDocument();
    expect(screen.getByText('paprika')).toBeInTheDocument();

    const steps = screen.getAllByRole('listitem').filter((li) => /Simmer|Crack/.test(li.textContent ?? ''));
    expect(steps).toHaveLength(2);
    expect(within(steps[0]).getByText('1')).toBeInTheDocument();
    expect(within(steps[1]).getByText('2')).toBeInTheDocument();

    expect(screen.getByText('Made with Groq')).toBeInTheDocument();
    expectNoEmoji();
  });

  it('says so when no allergens are found, and hides the extras group and unknown provider', async () => {
    signedIn();
    server.use(
      http.get(`${BASE}/api/users/me/ai-recipes/a-1`, () =>
        HttpResponse.json(recipeFor({
          allergens: [], provider: 'other',
          ingredients: [{ name: 'rice', amount: '1 cup', extra: false }],
          diets: { vegetarian: false, vegan: false, glutenFree: false, dairyFree: false },
        }))),
    );
    renderApp('/ai-recipes/a-1');

    expect(await screen.findByText('No listed allergens found')).toBeInTheDocument();
    expect(screen.queryByText(/You'll also need/)).not.toBeInTheDocument();
    expect(screen.queryByText(/Made with/)).not.toBeInTheDocument();
    expectNoEmoji();
  });

  it('shows Made with Gemini for the gemini provider', async () => {
    signedIn();
    server.use(
      http.get(`${BASE}/api/users/me/ai-recipes/a-1`, () => HttpResponse.json(recipeFor({ provider: 'gemini' }))),
    );
    renderApp('/ai-recipes/a-1');
    expect(await screen.findByText('Made with Gemini')).toBeInTheDocument();
  });

  it('shows "Page not found." for a recipe that is not the user\'s', async () => {
    signedIn();
    server.use(
      http.get(`${BASE}/api/users/me/ai-recipes/a-1`, () =>
        HttpResponse.json({ detail: 'Not found' }, { status: 404 })),
    );
    renderApp('/ai-recipes/a-1');
    expect(await screen.findByText('Page not found.')).toBeInTheDocument();
    expectNoEmoji();
  });

  it('saves with PUT then shows Saved, and clicking Saved sends DELETE', async () => {
    signedIn();
    let saved = false;
    const calls: string[] = [];
    server.use(
      http.get(`${BASE}/api/users/me/ai-recipes/a-1`, () => HttpResponse.json(recipeFor({ saved }))),
      http.put(`${BASE}/api/users/me/ai-recipes/a-1/saved`, () => {
        calls.push('PUT'); saved = true; return new HttpResponse(null, { status: 204 });
      }),
      http.delete(`${BASE}/api/users/me/ai-recipes/a-1/saved`, () => {
        calls.push('DELETE'); saved = false; return new HttpResponse(null, { status: 204 });
      }),
    );
    const user = userEvent.setup();
    renderApp('/ai-recipes/a-1');

    await user.click(await screen.findByRole('button', { name: 'Save' }));
    const savedButton = await screen.findByRole('button', { name: 'Saved' });
    expect(calls).toEqual(['PUT']);

    await user.click(savedButton);
    await screen.findByRole('button', { name: 'Save' });
    await waitFor(() => expect(calls).toEqual(['PUT', 'DELETE']));
    expectNoEmoji();
  });
});

